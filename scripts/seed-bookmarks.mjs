#!/usr/bin/env node
/**
 * Seeds D1 from content/bookmarks.json, once.
 *
 * The catalogue lived in that file and the API mutated it in place, so without
 * a seed the move to D1 would appear to lose all ~550 bookmarks. Rows are
 * inserted in batches inside one implicit transaction per batch; `INSERT OR
 * REPLACE` makes a re-run idempotent.
 *
 * After this has run, the JSON file is no longer read by anything and can be
 * removed. It is kept for now so this can be re-run if the seed needs fixing.
 */
import fs from 'fs'
import path from 'path'

const SRC = path.join(process.cwd(), 'content', 'bookmarks.json')

if (!fs.existsSync(SRC)) {
  console.log('content/bookmarks.json not found, nothing to seed')
  process.exit(0)
}

const raw = JSON.parse(fs.readFileSync(SRC, 'utf-8'))

/**
 * Emits a literal .sql file rather than a {sql, params} JSON.
 *
 * `wrangler d1 execute --file` parses the file as SQL text; a JSON statement
 * list is silently accepted and then runs 0 statements, which left the table
 * empty without raising an error. So every value is inlined with '' escaping.
 */
const esc = (v) => `'${String(v ?? '').replace(/'/g, "''")}'`

const rows = raw.map((b) => {
  const tags = JSON.stringify(Array.isArray(b.tags) ? b.tags : []).replace(
    /'/g,
    "''",
  )
  const values = [
    esc(b.id),
    esc(b.title),
    esc(b.url),
    esc(b.description ?? ''),
    esc(b.category),
    `'${tags}'`,
    b.faviconUrl ? esc(b.faviconUrl) : 'NULL',
    b.featured ? 1 : 0,
    esc(b.createdAt ?? new Date().toISOString()),
  ].join(', ')

  return `INSERT OR REPLACE INTO bookmarks (id,title,url,description,category,tags,favicon_url,featured,created_at) VALUES (${values});`
})

const outFile = path.join(process.cwd(), '.bookmarks-seed.sql')

// No BEGIN/COMMIT wrapper: `wrangler d1 execute --file` splits on semicolons and
// dispatches each statement in its own implicit transaction. An explicit
// wrapping transaction across 559 statements was accepted and then rolled back
// with no error, leaving the table empty.
fs.writeFileSync(
  outFile,
  [
    '-- Generated by scripts/seed-bookmarks.mjs from content/bookmarks.json.',
    '-- One-off migration of the catalogue into D1. Safe to re-run:',
    '-- every statement is INSERT OR REPLACE keyed on the original id.',
    ...rows,
    '',
  ].join('\n'),
  'utf-8',
)

console.log(`prepared ${rows.length} bookmark rows -> ${path.relative(process.cwd(), outFile)}`)